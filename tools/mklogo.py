#!/usr/bin/env python3
"""The title screen's logo (art/logo.png, grey and alpha) as C: src/logo.c, its grey level and
alpha a pixel each. Usage: tools/mklogo.py"""
import pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
im = Image.open(root / 'art/logo.png').convert('LA')
w, h = im.size
px = im.tobytes()  # grey, alpha, grey, alpha...
lines = ['/* Generated by tools/mklogo.py from art/logo.png: grey then alpha, a pixel each. */',
         '#include "hero.h"', '', f'const int logo_w = {w}, logo_h = {h};', 'const unsigned char logo_px[] = {']
for i in range(0, len(px), 32):
    lines.append('    ' + ','.join(str(b) for b in px[i:i + 32]) + ',')
lines.append('};')
(root / 'src/logo.c').write_text('\n'.join(lines) + '\n')
print(f'logo: {w} x {h}')
