#!/usr/bin/env python3
"""The game's fonts as anti-aliased alpha bitmaps in C: src/fontdata.c. Usage: tools/mkfont.py

  F_SMALL  Fira Sans Medium 14 px     lists and hints: Latin, Greek and Cyrillic, so song names show
  F_MED    Fira Sans SemiBold 18 px   titles: the same characters
  F_BIG    Anton 28 px                headings, numbers: ASCII
  F_HUGE   Anton 60 px                the logo and big call-outs: capitals, digits, a few marks

Fira Sans (Mozilla, Carrois) and Anton (Vernon Adams) are under the SIL Open Font License 1.1:
tools/OFL-FiraSans.txt and tools/OFL-Anton.txt. Needs Pillow and fontTools; the output is
committed, so a build needs neither."""
import pathlib
from PIL import ImageFont
from fontTools.ttLib import TTFont

GF = '/usr/share/fonts/truetype/google-fonts/ofl/'
FIRA_M, FIRA_SB, ANTON = GF + 'firasans/FiraSans-Medium.ttf', GF + 'firasans/FiraSans-SemiBold.ttf', GF + 'anton/Anton-Regular.ttf'

def ranges(*rs):
    out = []
    for a, b in rs:
        out += range(a, b + 1)
    return out

TEXT = ranges((0x20, 0x7e), (0xa0, 0x17f), (0x18f, 0x192), (0x1a0, 0x1b0), (0x218, 0x21b), (0x386, 0x3ce),
              (0x400, 0x45f), (0x490, 0x491), (0x1e9e, 0x1e9e), (0x2010, 0x2027), (0x2030, 0x203a),
              (0x20ac, 0x20ac), (0x2116, 0x2116), (0x2122, 0x2122))
ASCII = ranges((0x20, 0x7e))
LOGO = [ord(c) for c in ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!%.,:x+-?\'/']
FONTS = [('small', FIRA_M, 14, TEXT), ('med', FIRA_SB, 18, TEXT), ('big', ANTON, 28, ASCII), ('huge', ANTON, 60, LOGO)]

out = ['/* Generated by tools/mkfont.py: Fira Sans and Anton (SIL OFL 1.1) as alpha bitmaps. */',
       '#include "hero.h"', '']
for name, path, size, chars in FONTS:
    cmap = TTFont(path).getBestCmap()
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    glyphs, px = [], bytearray()
    for cp in sorted(set(chars)):  # sorted: the game looks glyphs up by binary search
        if cp != 0x20 and cp not in cmap:
            continue
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        if cp == 0x20 or not ch.strip():
            glyphs.append((cp, 0, 0, 0, 0, adv, 0))
            continue
        im, (ox, oy) = f.getmask2(ch, mode='L')
        w, h = im.size
        data = bytes(im)
        # trim empty rows and columns
        rows = [y for y in range(h) if any(data[y * w:(y + 1) * w])]
        cols = [x for x in range(w) if any(data[y * w + x] for y in range(h))]
        if not rows:
            glyphs.append((cp, 0, 0, 0, 0, adv, 0))
            continue
        y0, y1, x0, x1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
        off = len(px)
        for y in range(y0, y1):
            px += data[y * w + x0:y * w + x1]
        glyphs.append((cp, x1 - x0, y1 - y0, ox + x0, oy + y0, adv, off))
    out.append(f'static const Glyph g_{name}[] = {{')
    for g in glyphs:
        out.append('    {%d, %d, %d, %d, %d, %d, %d},' % g)
    out.append('};')
    out.append(f'static const unsigned char p_{name}[] = {{')
    for i in range(0, len(px), 32):
        out.append('    ' + ','.join(str(b) for b in px[i:i + 32]) + ',')
    out.append('};')
    out.append(f'const FontData font_{name} = {{ {size}, {asc}, {desc}, {len(glyphs)}, g_{name}, p_{name} }};')
    out.append('')
    print(f'{name}: {len(glyphs)} glyphs, {len(px)} bytes, ascent {asc}, descent {desc}')
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/fontdata.c').write_text('\n'.join(out))
